# 默认免费的关键词（这些几乎都是免费景点）
ALWAYS_FREE_KEYWORDS = [
    '广场', '绿地', '步行街', '夜景', '海滩', '沙滩',
    '保护区', '湿地', '老街', '古街', '码头', '观景台',
]


def is_always_free(name):
    """判断是否一定免费的景点"""
    for kw in ALWAYS_FREE_KEYWORDS:
        if kw in name:
            return True
    return False


def get_price_by_keyword(name):
    """通过关键词匹配获取价格"""
    for kw, price in KEYWORD_RULES:
        if kw in name:
            return price
    return None


def update_ticket_prices():
    """更新景点门票价格"""
    db = SessionLocal()
    try:
        attractions = db.query(Attraction).all()
        updated = 0
        exact_matched = 0
        keyword_matched = 0
        already_correct = 0
        no_match = 0
        
        for a in attractions:
            old_price = a.ticket_price or 0
            new_price = None
            
            # 1. 先查精确匹配
            city_prices = EXACT_PRICES.get(a.city, {})
            if a.name in city_prices:
                new_price = city_prices[a.name]
                exact_matched += 1
            else:
                # 2. 关键词匹配
                kw_price = get_price_by_keyword(a.name)
                if kw_price is not None:
                    new_price = kw_price
                    keyword_matched += 1
            
            if new_price is not None and new_price != old_price:
                a.ticket_price = float(new_price)
                updated += 1
                print(f"  [{a.city}] {a.name}: {old_price} -> {new_price}元")
            elif new_price is not None and new_price == old_price:
                already_correct += 1
            else:
                no_match += 1
        
        db.commit()
        
        print(f"\n{'='*50}")
        print(f"门票价格更新完成！")
        print(f"  总景点数: {len(attractions)}")
        print(f"  精确匹配更新: {exact_matched}")
        print(f"  关键词匹配更新: {keyword_matched}")
        print(f"  已是正确价格: {already_correct}")
        print(f"  无匹配(保留原价): {no_match}")
        print(f"  实际更新: {updated}")
        
    except Exception as e:
        db.rollback()
        print(f"更新失败: {e}")
        import traceback
        traceback.print_exc()
    finally:
        db.close()


if __name__ == '__main__':
    update_ticket_prices()
